#!/bin/python
import os
import struct
import sys
from collections import OrderedDict, deque
import io
import csv
from functools import partial, reduce

sys.path.append(os.path.join(os.path.dirname(__file__), 'common'))
from common import utils, tilesets
from sw2gb import game

# The set of scenes [ADDR:2LE]
SCENE_BANK = 0x23
SCENE_TABLE_START = (SCENE_BANK, 0x410A)
SCENE_TABLE_END = (SCENE_BANK, 0x4292)
# For now, we just forcibly ignore the last 3 which are empty
SCENE_TABLE_COUNT = ((SCENE_TABLE_END[1] - SCENE_TABLE_START[1]) // 2)
SCRIPTS_END = (SCENE_BANK, 0x61e8 + 1)

# Arguments
script_name = sys.argv[0]
rom_path = sys.argv[1]
game_scene_src_dir = sys.argv[2]
game_scene_script_dir = sys.argv[3]
game_scene_npc_script_dir = sys.argv[4]

game_scene_npc_charmap = os.path.join(game_scene_npc_script_dir, f'charmap.asm')

# Load tileset info
character_table = tilesets.get_tileset("GameSceneNPCScript", override_offset=0x00)

gs = game.GameSceneScript(character_table)
GS_COMMANDS = gs.COMMANDS

with open(os.path.join(game_scene_src_dir, f'commands.asm'), 'w') as commands_fp:
    for command in GS_COMMANDS:
        if GS_COMMANDS[command].command_macro is None:
            commands_fp.write(f'MACRO {GS_COMMANDS[command].name}\n')
            commands_fp.write(f'  db ${command:02X}\n')
            commands_fp.write(f'  IF _NARG > 0\n')
            commands_fp.write(f'    db \\#\n')
            commands_fp.write(f'  ENDC\n')
            commands_fp.write(f'ENDM\n\n')
        else:
            commands_fp.write(f'MACRO {GS_COMMANDS[command].name}\n')
            commands_fp.write(f'  db ${command:02X}\n')
            for idx, macro in enumerate(GS_COMMANDS[command].command_macro):
                commands_fp.write(f'  {macro} \\{idx + 1}\n')
            commands_fp.write(f'ENDM\n\n')

with open(rom_path, 'rb') as rom:
    # Get the list of scenes
    scene_addresses = []
    rom.seek(utils.rom2realaddr(SCENE_TABLE_START))
    for index in range(0, SCENE_TABLE_COUNT):
        scene_addresses.append(utils.read_short(rom))

    scenes = { k : f'GameScene{v:02X}' for v, k in enumerate(sorted(list(set(scene_addresses)))) }

    # For each scene, there's some set of scripts
    # Scripts can be shared between multiple scenes
    script_addresses = OrderedDict()
    for addr in scene_addresses:
        rom.seek(utils.rom2realaddr((SCENE_BANK, addr)))
        script_addresses[addr] = list(iter(partial(utils.read_short, rom), 0x00))

    # Maintain a unique set of every script to dump
    scripts = { k : f'GameSceneScript{v:04X}' for v, k in enumerate(sorted(list(set(reduce(lambda x, y: x + y, script_addresses.values()))))) }

    with open(os.path.join(game_scene_src_dir, f'game_scene_table.asm'), 'w') as scene_table_fp:
        scene_table_fp.write(f"; File initially autogenerated by {script_name}\n")
        scene_table_fp.write('\n')
        scene_table_fp.write('INCLUDE "game/src/common/macros.asm"\n')
        scene_table_fp.write('\n')

        for x in range(0, len(scenes)):
            scene_table_fp.write(f'INCLUDE "{os.path.join(game_scene_script_dir, f"game_scene_{x:02X}.asm")}"\n')
        scene_table_fp.write('\n')

        scene_table_fp.write(f'SECTION "Game Scene Table", ROMX[${SCENE_TABLE_START[1]:04X}], BANK[${SCENE_TABLE_START[0]:02X}]\n')
        scene_table_fp.write('GameSceneTable::\n')
        for x in scene_addresses:
            scene_table_fp.write(f'  dw {scenes[x]}\n')
        scene_table_fp.write('\n')

        for index, addr in enumerate(script_addresses):
            with open(os.path.join(game_scene_script_dir, f'game_scene_{index:02X}.asm'), 'w') as scene_fp:
                scene_fp.write(f"; File initially autogenerated by {script_name}\n")
                scene_fp.write(f'SECTION "Game Scene {index:02X}", ROMX[${addr:04X}], BANK[${SCENE_BANK:02X}]\n')
                scene_fp.write(f'GameScene{index:02X}::\n')
                for x in script_addresses[addr]:
                    scene_fp.write(f'  dw {scripts[x]}\n')
                scene_fp.write('  dw $0000\n')

    # TODO: For now, just dump scripts as bytes in a single file
    with open(os.path.join(game_scene_src_dir, f'game_scene_scripts.asm'), 'w') as script_fp:
        script_fp.write(f"; File initially autogenerated by {script_name}\n")
        script_fp.write('\n')
        script_fp.write(f'INCLUDE "game/src/common/macros.asm"\n')
        script_fp.write(f'INCLUDE "{os.path.join(game_scene_src_dir, f"commands.asm")}"\n')
        script_fp.write('\n')
        scene_addr = iter(list(script_addresses.keys()) + [0x7fff])
        next_scene_address = next(scene_addr)
        script_addr = sorted(list(scripts.keys()))
        script_addr += [SCRIPTS_END[1]]

        npc_data = []

        for index in range(0, len(script_addr) - 1):
            rom.seek(utils.rom2realaddr((SCENE_BANK, script_addr[index])))
            while next_scene_address < script_addr[index]:
                next_scene_address = next(scene_addr)
            l = min(next_scene_address, script_addr[index + 1]) - script_addr[index]
            data = rom.read(l)
            script_fp.write(f'SECTION "Game Scene Script {index:04X}", ROMX[${script_addr[index]:04X}], BANK[${SCENE_BANK:02X}]\n')
            script_fp.write(f'{scripts[script_addr[index]]}::\n')

            if l == 0:
                continue

            script_fp.write(f'  db ${data[0]:02X}, ${data[1]:02X} ; (x, y)\n')

            command = None
            i = 2
            terminator_code = None
            while i < l:
                # Parse each byte of the script to generate a list of script functions
                try:
                    if len(data[i:]) >= 2 and terminator_code == data[i:i+2]:
                        script_fp.write(f'  db ${terminator_code[0]:02X}, ${terminator_code[1]:02X}\n')
                        break
                    command = GS_COMMANDS[data[i]]
                except KeyError:
                    # TODO: For now, break early when we see things that seem out of place
                    if data[i] > 0x25:
                        break
                    print(f"No handler for command ${data[i]:02X} @ ${SCENE_BANK:02X}:${script_addr[index]+i:04X}")
                    exit(1)

                p = command.read_handler(data[i+1:])
                parameter_size = p.length
                parameters = p.parameters
                texts = p.texts
                references = p.reference_offsets
                assert parameter_size != 0 or (parameters is None and texts is None and references is None)

                # It seems 0x20 indicates a label, need to investigate
                if data[i] == 0x20:
                    terminator_code = parameters

                try:
                    line = f"  {command.name}"
                    if parameter_size > 0:
                        line += " "

                    parameters_str = []
                    if parameters is not None:
                        parameters_str = [f'${x:02X}' for x in parameters]
                    elif texts is not None:
                        text_index = len(npc_data) if utils.rom2realaddr(texts) not in npc_data else npc_data.index(utils.rom2realaddr(texts))
                        text_name = f'GameSceneNPCScript{text_index:04X}'
                        parameters_str = [f'{text_name}', f'BANK({text_name})']
                        if utils.rom2realaddr(texts) not in npc_data:
                            npc_data.append(utils.rom2realaddr(texts))

                    parameters_data = io.StringIO()
                    c = csv.writer(parameters_data, lineterminator='', delimiter=',', quotechar='"', quoting=csv.QUOTE_MINIMAL)
                    c.writerow(parameters_str)

                    line += parameters_data.getvalue()
                    script_fp.write(f'{line}\n')
                finally:
                    i += 1 + parameter_size

            # if l > 0:
            #
            #     script_fp.write(f'  db {",".join([f"${x:02X}" for x in data[2:]])}\n')
            script_fp.write('\n')


    # NPC scripts follow a different set of commands from the Game Scenes themselves
    # There is also no table to help identify their sizes, so termination commands must be used
    reference_map = {}
    reference_count = 0
    handled_references = []
    initial_references = []

    to_parse = deque()
    def add_reference(bank, addr, data_terminator, data_count, data_type):
        global reference_count
        global reference_map

        real_addr = utils.rom2realaddr((bank, addr))
        
        if real_addr in reference_map and reference_map[real_addr][0] == False:
            return reference_map[real_addr][1]

        if real_addr in reference_map:
            reference_map[real_addr] = (True, reference_map[real_addr][1])
        else:
            reference_map[real_addr] = (False, reference_count)
            reference_count += 1

        reference_id = reference_map[real_addr][1]
        to_parse.append((reference_id, bank, addr, data_terminator, data_count, data_type))

        return reference_id

    def do_write_line(write_line, ls, l):
        if write_line:
            ls.append(l)

    files = {}

    for write_stage in range(2):
        write_line = write_stage == 1

        # On subsequent runs, make sure we run through and parse as necessary
        for reference_addr in reference_map:
            reference_map[reference_addr] = (True, reference_map[reference_addr][1])

        prefix = f'GameSceneNPCScript'
        for index, addr in enumerate(npc_data):
            rom_addr = utils.real2romaddr(addr)
            file_path = os.path.join(game_scene_npc_script_dir, f'game_scene_npc_script_{index:04X}.asm')
            files[file_path] = []
            lines = files[file_path]

            title = f'Game Scene NPC Script {index:04X}'
            do_write_line(write_line, lines, 'PUSHC\n')
            do_write_line(write_line, lines, f'INCLUDE "game/src/common/macros.asm"')
            do_write_line(write_line, lines, f'INCLUDE "{game_scene_npc_charmap}"\n')
            do_write_line(write_line, lines, f'SECTION "{title}", ROMX[${rom_addr[1]:04X}], BANK[${rom_addr[0]:02X}]')
            do_write_line(write_line, lines, f'{prefix}{index:04X}::')
            rom.seek(addr)

            if index + 1 > len(initial_references):
                initial_references.append(reference_count)
            initial_reference = initial_references[index]

            # Queue up data to parse out
            initial_written = False
            add_reference(rom_addr[0], rom_addr[1], None, None, None)
            current_bank = rom_addr[0]
            is_term = False

            while len(to_parse) > 0:
                val = to_parse.popleft()
                if type(val) is int:
                    # Parse command locally
                    # TODO: Use command class
                    # TODO: Use parameter data + csv writer

                    if val == 0x00:
                        # Write text from [addr:2LE], [Bank]
                        # Text is terminated by $00
                        addr = utils.read_byte(rom) | (utils.read_byte(rom) << 8)
                        bank = utils.read_byte(rom)
                        reference_id = add_reference(bank, addr, 0x00, 1, "Text")
                        do_write_line(write_line, lines, f'  db ${val:02X} ; WriteText')
                        do_write_line(write_line, lines, f'    dwb {prefix}Reference{reference_id:04X}, BANK({prefix}Reference{reference_id:04X})')
                    elif val == 0x01:
                        # Timed choice
                        is_term = True
                        arg1 = utils.read_byte(rom) # Counter speed
                        arg2 = utils.read_byte(rom) # Length?
                        do_write_line(write_line, lines, f'  db ${val:02X} ; TimedOption')
                        do_write_line(write_line, lines, f'    db ${arg1:02X} ; Available Time')
                        do_write_line(write_line, lines, f'    db ${arg2:02X}')

                        while True:
                            addr = utils.read_byte(rom) | (utils.read_byte(rom) << 8)
                            if addr == 0xFFFF:
                                do_write_line(write_line, lines, f'    dw $FFFF')
                                break
                            bank = utils.read_byte(rom)
                            reference_id = add_reference(bank, addr, 0x00, 1, "Text")
                            do_write_line(write_line, lines, f'    dwb {prefix}Reference{reference_id:04X}, BANK({prefix}Reference{reference_id:04X}) ; Text')
                            addr = utils.read_byte(rom) | (utils.read_byte(rom) << 8)
                            if addr == 0xFFFF:
                                do_write_line(write_line, lines, f'    dw $FFFF')
                                break
                            reference_id = add_reference(current_bank, addr, None, None, None)
                            do_write_line(write_line, lines, f'    dw {prefix}Reference{reference_id:04X} ; Option Branch')
                    elif val == 0x02:
                        # Not sure
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x05:
                        # Combat
                        arg1 = utils.read_byte(rom)
                        arg2 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Combat')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                        do_write_line(write_line, lines, f'    db ${arg2:02X}')
                    elif val == 0x06:
                        # Not sure
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                    elif val == 0x07:
                        # Probably setting portrait
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Portrait')
                        do_write_line(write_line, lines, f'    db ${utils.read_byte(rom):02X}')
                    elif val == 0x09:
                        # Not sure
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x08:
                        # Local branch
                        addr = utils.read_byte(rom) | (utils.read_byte(rom) << 8)
                        reference_id = add_reference(current_bank, addr, None, None, None)
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Local Branch')
                        do_write_line(write_line, lines, f'    dw {prefix}Reference{reference_id:04X}')
                        while arg1 != 0x00:
                            if arg1 == 0x07:
                                # Seems to be an indicator that there's a next byte to read
                                do_write_line(write_line, lines, f'    db ${arg1:02X}')
                                arg1 = utils.read_byte(rom)
                            arg2 = utils.read_byte(rom)
                            arg3 = utils.read_byte(rom)
                            arg4 = utils.read_byte(rom)
                            do_write_line(write_line, lines, f'    db ${arg1:02X}')
                            do_write_line(write_line, lines, f'    db ${arg2:02X}')
                            do_write_line(write_line, lines, f'    db ${arg3:02X}')
                            do_write_line(write_line, lines, f'    db ${arg4:02X}')
                            arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x0A:
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Sound effect')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x0B:
                        # Not sure
                        arg1 = utils.read_byte(rom)
                        arg2 = utils.read_byte(rom)
                        arg3 = utils.read_byte(rom)
                        arg4 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                        do_write_line(write_line, lines, f'    db ${arg2:02X}')
                        do_write_line(write_line, lines, f'    db ${arg3:02X}')
                        do_write_line(write_line, lines, f'    db ${arg4:02X}')
                    elif val == 0x0C:
                        # Not sure
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x0D:
                        # Not sure
                        arg1 = utils.read_byte(rom)
                        arg2 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                        do_write_line(write_line, lines, f'    db ${arg2:02X}')
                    elif val == 0x0E:
                        # Seems to be when allies pop up for a scene
                        arg1 = utils.read_byte(rom)
                        arg2 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Ally Split')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                        do_write_line(write_line, lines, f'    db ${arg2:02X}')
                    elif val == 0x0F:
                        # Maybe sound effects? Not sure...
                        arg1 = utils.read_byte(rom)
                        arg2 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                        do_write_line(write_line, lines, f'    db ${arg2:02X}')
                    elif val == 0x10:
                        # Not sure
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x11:
                        # Not sure
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x12:
                        # Special move? 12 31 seems to push the sprite down
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x13:
                        # Not sure
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x14:
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Change scene')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x15:
                        # Not sure
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x16:
                        # Move character in a direction
                        arg1 = utils.read_byte(rom)
                        arg2 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Move character')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                        do_write_line(write_line, lines, f'    db ${arg2:02X}')
                    elif val == 0x17:
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Spawn Visual Entity')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x18:
                        # N options until we hit 0xFFFF
                        is_term = True
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Option Select')
                        while True:
                            addr = utils.read_byte(rom) | (utils.read_byte(rom) << 8)
                            bank = utils.read_byte(rom)
                            if addr == 0xFFFF:
                                do_write_line(write_line, lines, f'    dw $FFFF')
                                break
                            reference_id = add_reference(bank, addr, 0x00, 1, "Text")
                            # Text
                            do_write_line(write_line, lines, f'    dwb {prefix}Reference{reference_id:04X}, BANK({prefix}Reference{reference_id:04X}) ; Text')
                            addr = utils.read_byte(rom) | (utils.read_byte(rom) << 8)
                            if addr == 0xFFFF:
                                do_write_line(write_line, lines, f'    dw $FFFF')
                                break
                            # Option branch
                            reference_id = add_reference(current_bank, addr, None, None, None)
                            do_write_line(write_line, lines, f'    dw {prefix}Reference{reference_id:04X} ; Option Branch')
                    elif val == 0x19:
                        # Not sure
                        arg1 = utils.read_byte(rom)
                        arg2 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                        do_write_line(write_line, lines, f'    db ${arg2:02X}')
                    elif val == 0x1A:
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Spawn/spin in entity')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x1B:
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Chest')
                        do_write_line(write_line, lines, f'    db ${arg1:02X} ; Item in chest')
                    elif val == 0x1C:
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Chest 2')
                        do_write_line(write_line, lines, f'    db ${arg1:02X} ; Item in chest')
                    elif val == 0x1D:
                        arg1 = utils.read_byte(rom)
                        addr = utils.read_byte(rom) | (utils.read_byte(rom) << 8)
                        reference_id = add_reference(current_bank, addr, None, None, None)
                        arg3 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Timer')
                        do_write_line(write_line, lines, f'    db ${arg1:02X} ; Available Time') # Lower is smaller
                        do_write_line(write_line, lines, f'    dw {prefix}Reference{reference_id:04X} ; On Timer Branch')
                        do_write_line(write_line, lines, f'    db ${arg3:02X}')
                        is_term = True # Not sure about this
                    elif val == 0x1E:
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                    elif val == 0x1F:
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                    elif val == 0x20:
                        # Effect
                        arg1 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Visual Effect')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                    elif val == 0x21:
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                    elif val == 0x23:
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                    elif val == 0x25:
                        arg1 = utils.read_byte(rom)
                        arg2 = utils.read_byte(rom)
                        do_write_line(write_line, lines, f'  db ${val:02X} ; Incrementing Timer')
                        do_write_line(write_line, lines, f'    db ${arg1:02X}')
                        do_write_line(write_line, lines, f'    db ${arg2:02X} ; Max Seconds')
                    elif val == 0x26:
                        # If Male/Female
                        addr = utils.read_byte(rom) | (utils.read_byte(rom) << 8)
                        bank = utils.read_byte(rom)
                        option1_reference_id = add_reference(bank, addr, None, None, None)
                        addr = utils.read_byte(rom) | (utils.read_byte(rom) << 8)
                        bank = utils.read_byte(rom)
                        option2_reference_id = add_reference(bank, addr, None, None, None)
                        do_write_line(write_line, lines, f'  db ${val:02X}')
                        do_write_line(write_line, lines, f'    dwb {prefix}Reference{option1_reference_id:04X}, BANK({prefix}Reference{option1_reference_id:04X}) ; If Male')
